"""Reproducible authored-fixture checks, deliberately not a model research study."""

from __future__ import annotations

import argparse
import asyncio
import json
import platform
import random
import statistics
import tempfile
from pathlib import Path

from workevo import (
    Limits,
    Node,
    Optimizer,
    SequenceProposer,
    Skill,
    Store,
    Workflow,
    authored_dataset,
    builtin_registry,
    seed_skill,
)
from workevo.contracts import digest, implementation_identity
from workevo.optimization import FeedbackProposer
from workevo.registry import atomic_write
from workevo.reporting import report


class RandomEdits:
    def __init__(self, seed: int) -> None:
        self.seed = seed

    @property
    def identity(self) -> str:
        return f"random-flags-v1:{self.seed}"

    async def propose(self, request, store, study):
        rng = random.Random(self.seed * 1000 + request.iteration)
        return Skill(
            skill_id=request.parent.skill_id,
            family=request.parent.family,
            instructions=request.parent.instructions,
            parents=(request.parent.revision,),
            hypothesis="Random flags and redundant-step choice",
            workflow=workflow(
                rng.choice([False, True]), rng.choice([False, True]), rng.choice([False, True])
            ),
        )


class InstructionsOnly:
    identity = "instruction-only-v1"

    async def propose(self, request, store, study):
        if request.iteration >= 3:
            return None
        return request.parent.model_copy(
            update={
                "parents": (request.parent.revision,),
                "instructions": request.parent.instructions
                + f" Check normalization carefully ({request.iteration}).",
                "hypothesis": "Instruction-only ablation; deterministic executor does not consume text",
            }
        )


def workflow(aliases: bool, trim: bool, audit: bool) -> Workflow:
    nodes = (
        Node(
            id="normalize",
            operator="normalize_record",
            parameters={"aliases": aliases, "trim": trim},
            next="audit" if audit else "done",
        ),
    )
    if audit:
        nodes += (Node(id="audit", operator="identity"),)
    return Workflow(entry="normalize", nodes=nodes)


async def run(output: Path, repeats: int) -> None:
    dataset = authored_dataset()
    policy = {"repeats": 1, "quality_floor": 0, "min_gain": 0, "patience": 3}
    protocol = {
        "version": 1,
        "dataset_hash": dataset.revision,
        "methods": [
            "unchanged_seed",
            "authored_reference",
            "random_edits",
            "development_feedback",
            "instruction_only",
        ],
        "seeds": list(range(repeats)),
        "limits": Limits(candidates=6).model_dump(mode="json"),
        "policy": policy,
        "evidence_kind": "authored_software_fixture",
        "test_access": "only after study freeze",
        "analysis": "Raw per-case trials; across-seed mean and range. No statistical claim about model capability.",
        "limitations": [
            "Reference workflow is manually authored, not generated by a model.",
            "Instruction text has no effect on the deterministic normalizer.",
            "No SkillOpt, GEPA or AFlow execution.",
            "No independent annotation review or live model.",
        ],
    }
    # Persist the protocol before any search is run.
    atomic_write(
        output.with_name(output.stem + "-protocol.json"), json.dumps(protocol, indent=2) + "\n"
    )
    records = []
    with (
        tempfile.TemporaryDirectory(prefix="workflow-software-study-") as directory,
        Store(Path(directory) / "study.sqlite") as store,
    ):
        for method in protocol["methods"]:
            for seed_number in range(repeats):
                seed = seed_skill()
                if method == "authored_reference":
                    seed = seed.model_copy(
                        update={
                            "workflow": workflow(True, True, False),
                            "hypothesis": "Manually authored reference control",
                        }
                    )
                proposer = (
                    {
                        "random_edits": lambda number=seed_number: RandomEdits(number),
                        "development_feedback": FeedbackProposer,
                        "instruction_only": InstructionsOnly,
                    }.get(method, lambda: SequenceProposer(()))
                )()
                optimizer = Optimizer(store, dataset, builtin_registry(), proposer)
                study = optimizer.create(seed, limits=Limits(candidates=6))
                result = await optimizer.run(study)
                optimizer.freeze(study)
                final = await optimizer.final_test(study)
                records.append(
                    {
                        "method": method,
                        "seed": seed_number,
                        "result": result.model_dump(mode="json"),
                        "final_quality": final["quality"],
                        "report": report(store, study, optimizer.evaluator),
                    }
                )
    aggregates = {}
    for method in protocol["methods"]:
        rows = [r for r in records if r["method"] == method]
        qualities = [r["final_quality"] for r in rows]
        aggregates[method] = {
            "mean_quality": statistics.mean(qualities),
            "min_quality": min(qualities),
            "max_quality": max(qualities),
            "mean_trials": statistics.mean(r["report"]["usage"]["trials"] for r in rows),
            "mean_tool_calls": statistics.mean(r["report"]["usage"]["tool_calls"] for r in rows),
        }
    result = {
        "schema_version": 1,
        "protocol_hash": digest(protocol),
        "protocol": protocol,
        "environment": {
            "python": platform.python_version(),
            "implementation_hash": implementation_identity(),
            "study_script_hash": digest(Path(__file__).read_text()),
            "platform": platform.platform(),
        },
        "runs": len(records),
        "trials": sum(r["report"]["usage"]["trials"] for r in records),
        "aggregates": aggregates,
        "records": records,
    }
    atomic_write(output, json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({k: result[k] for k in ("runs", "trials", "aggregates")}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path("reports/software-study.json"))
    parser.add_argument("--repeats", type=int, default=5)
    args = parser.parse_args()
    if not 1 <= args.repeats <= 20:
        parser.error("repeats must be 1..20")
    asyncio.run(run(args.output, args.repeats))
